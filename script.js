// ===== FUNCTION TO TOGGLE MOBILE MENU =====
function toggleMenu() {
    // Get navigation menu
    let nav = document.getElementById("navLinks");

    // Toggle 'active' class to show/hide menu
    nav.classList.toggle("active");
}


